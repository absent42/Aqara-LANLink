def _key4(key: str) -> bytes:
    """Build the per-key 4-byte selection table (CRCSelect4Key).

    The native code reads at most 20 bytes of the NUL-terminated key string.
    """
    raw = key.encode("latin-1")
    # strnlen(key, 20)
    nul = raw.find(b"\x00")
    if nul != -1:
        raw = raw[:nul]
    raw = raw[:20]

    s = 0      # running add        -> key4[0]
    neg = 0    # running subtract   -> key4[1]
    acc = 0    # weighted accumulator-> key4[2]
    x = 0      # running xor        -> key4[3]
    for b in raw:
        s = (s + b) & 0xFFFFFFFF
        neg = (neg - b) & 0xFFFFFFFF
        acc = (acc + ((b * 0xAB) >> 9)) & 0xFFFFFFFF
        x ^= b
    return bytes([s & 0xFF, neg & 0xFF, acc & 0xFF, x & 0xFF])


def _keystream_byte(key4: bytes, prev: int) -> int:
    """__P2P_Proprietary_SelectTableElement(key4, prev)."""
    idx = (key4[prev & 3] + prev) & 0xFF
    return TABLE[idx]


def encrypt(key: str, data: bytes) -> bytes:
    if not data:
        return b""
    key4 = _key4(key)
    out = bytearray(len(data))
    prev = 0  # previous ciphertext byte; 0 for the first position
    for i, p in enumerate(data):
        ks = _keystream_byte(key4, prev)
        c = ks ^ p
        out[i] = c
        prev = c
    return bytes(out)


def decrypt(key: str, data: bytes) -> bytes:
    if not data:
        return b""
    key4 = _key4(key)
    out = bytearray(len(data))
    prev = 0  # previous ciphertext byte; 0 for the first position
    for i, c in enumerate(data):
        ks = _keystream_byte(key4, prev)
        out[i] = ks ^ c
        prev = c  # chain on the ciphertext (input)
    return bytes(out)
