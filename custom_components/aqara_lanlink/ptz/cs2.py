"""Pure-Python reproduction of the CS2 Network / PPPP "proprietary" cipher.

Reverse-engineered from libPPCS_API.so (arm64), functions:
  cs2p2p__P2P_Proprietary_Encrypt / _Decrypt
  __P2P_Proprietary_SelectTableElement
  CRCSelect4Key (the per-key 4-byte table builder)

Algorithm
---------
The cipher is a self-synchronising stream cipher (CFB-like) over a fixed
256-byte substitution permutation table embedded in the library, plus a
4-byte "key table" derived from the (NUL-terminated, max 20 byte) key string.

Per-key 4-byte table (key4), computed over the key bytes b:
    key4[0] =  sum(b)            & 0xff      # running add
    key4[1] = -sum(b)            & 0xff      # running subtract
    key4[2] =  sum((b*0xab)>>9)  & 0xff      # weighted accumulator
    key4[3] =  xor(b)            & 0xff      # running xor

Keystream byte for output position i depends on the *previous ciphertext
byte* (prev), with prev == 0 for i == 0:
    idx = (key4[prev & 3] + prev) & 0xff
    ks  = TABLE[idx]

Encrypt:  c[i] = ks(prev=c[i-1]) ^ p[i]      (chains on output/ciphertext)
Decrypt:  p[i] = ks(prev=c[i-1]) ^ c[i]      (chains on input/ciphertext)

Both directions chain on the ciphertext, so they are exact inverses.
The library has a SIMD fast path for the key4 computation; it is numerically
identical to the scalar definition above.
"""

